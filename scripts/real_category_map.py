def label(category: str, path: list[str], name: str):
    """-> (work_types | None если товар не размечается, kind). path — путь от корня, включая категорию."""
    root = path[0] if path else "?"
    if root in UNLABELED_ROOTS:
        return None, None
    full = " / ".join(path)
    if root not in REPAIR_ROOTS or category in NONE_NAMES:
        return [], "other"
    wt, kind = CAT.get(category, (None, None))
    if wt is None:
        for pat, (w, k) in PATH_RULES:
            if re.search(pat, full):
                wt, kind = w, k
                break
    if wt is None:
        return [], "other"
    if category in FAN_CATEGORIES:
        kind = "fan"
    n = name.lower()
    for pat, cond, w, k in KIND_OVERRIDES_BY_NAME:
        # условие: регэксп по имени категории («^...») или имя категории / элемент пути
        cond_ok = re.search(cond, category) if cond.startswith("^") else cond in path
        if cond_ok and re.search(pat, n):
            return list(w), k
    return list(wt), kind
